func rgb(r, g, b uint8) color.NRGBA { return color.NRGBA{R: r, G: g, B: b, A: 0xff} }

func ThemeIndex(name string) int {
	for i, t := range Themes {
		if equalFold(t.Name, name) {
			return i
		}
	}
	return -1
}

// ResolveTheme returns the theme matching name, or the default (index 0).
func ResolveTheme(name string) Palette {
	if i := ThemeIndex(name); i >= 0 {
		return Themes[i]
	}
	return Themes[0]
}
